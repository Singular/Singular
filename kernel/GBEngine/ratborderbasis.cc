BOOLEAN nc_RationalWeylBorderBasis(const ideal G, int coefficientVariables,
                                   ideal &orderIdeal, ideal &borderBasis,
                                   const ring r)
{
  orderIdeal = NULL;
  borderBasis = NULL;
  if (!rIsPluralRing(r))
  {
    WerrorS("rational Weyl border basis: expected a noncommutative G-algebra");
    return TRUE;
  }
  if ((coefficientVariables <= 0) || (coefficientVariables >= r->N))
  {
    WerrorS("rational Weyl border basis: invalid coefficient-variable block");
    return TRUE;
  }
  if (!rHasGlobalOrdering(r))
  {
    WerrorS("rational Weyl border basis: expected a global antiblock ordering");
    return TRUE;
  }

  const int firstOperator = coefficientVariables + 1;
  const int operators = r->N - coefficientVariables;
  borderbasis_kernel::ExponentVectors standard;
  borderbasis_kernel::ExponentVectors border;
  if (borderbasis_kernel::staircase(G, firstOperator, operators, standard,
                                    border, r))
    return TRUE;

  orderIdeal =
      borderbasis_kernel::makeMonomialIdeal(standard, firstOperator, r);
  borderBasis = idInit(static_cast<int>(border.size()), 1);
  for (size_t i = 0; i < border.size(); ++i)
  {
    poly b = borderbasis_kernel::makeMonomial(border[i], firstOperator, r);
    poly denominator = NULL;
    poly normalForm = rationalNormalForm(p_Copy(b, r), G,
                                         coefficientVariables, denominator, r);
    poly leadingPart = p_Mult_q(denominator, b, r);
    borderBasis->m[i] = p_Sub(leadingPart, normalForm, r);
  }
  return FALSE;
}

